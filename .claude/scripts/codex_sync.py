CODEX_BIN = Path("/Applications/ChatGPT.app/Contents/Resources/codex")


def verify(surfaces: list[Surface]) -> tuple[list[str], int]:
    """Ask the Codex binary what it actually loads in each repo.

    Static generation proves nothing on its own: Codex silently ignores a
    project-local plane until the project is trusted, and silently ignores a
    malformed skill. This asks the binary directly.
    """
    import subprocess
    import tomllib

    lines: list[str] = []
    failures = 0
    codex = shutil.which("codex") or (str(CODEX_BIN) if CODEX_BIN.exists() else None)
    if not codex:
        return ["codex binary not found — cannot verify"], 1

    for s in surfaces:
        if not s.codex.is_dir() and not (s.path / "AGENTS.md").is_file():
            continue
        problems: list[str] = []

        for toml_path in sorted((s.codex / "agents").glob("*.toml")):
            try:
                parsed = tomllib.loads(toml_path.read_text(encoding="utf-8"))
            except Exception as exc:  # noqa: BLE001 — report, don't crash the sweep
                problems.append(f"{toml_path.name} unparseable: {exc}")
                continue
            missing = [k for k in ("name", "description", "developer_instructions") if k not in parsed]
            if missing:
                problems.append(f"{toml_path.name} missing {missing}")

        try:
            done = subprocess.run(
                [codex, "debug", "prompt-input", "parity check"],
                cwd=s.path, capture_output=True, text=True, timeout=180,
            )
            blob = done.stdout
        except Exception as exc:  # noqa: BLE001
            problems.append(f"prompt-input failed: {exc}")
            blob = ""

        agents_md = s.path / "AGENTS.md"
        if agents_md.is_file() and blob:
            probe = next(
                (ln.strip() for ln in agents_md.read_text(encoding="utf-8").splitlines()
                 if ln.strip().startswith("# AGENTS.md")),
                "",
            )
            if probe and probe not in blob:
                problems.append("AGENTS.md not present in the loaded prompt")

        # Codex abbreviates the paths it reports and resolves symlinks, so match
        # on the `<name>/SKILL.md` tail rather than on the path we wrote.
        expected = sorted(
            p.parent.name for p in (s.codex / "skills").glob("*/SKILL.md")
        ) if (s.codex / "skills").is_dir() else []
        unseen = [n for n in expected if f"/{n}/SKILL.md" not in blob]
        if unseen:
            problems.append(f"{len(unseen)}/{len(expected)} skills not discovered: {unseen[:5]}")

        # Codex also reads `.agents/skills/`. In a repo we project, anything
        # there is outside the projection and can only be a stale surface
        # shadowing the real one. Vendored repos ship their own and keep it.
        rogue = sorted(p.parent.name for p in (s.path / ".agents" / "skills").glob("*/SKILL.md"))
        if rogue and s.name not in VENDORED:
            problems.append(
                f"{len(rogue)} skills in .agents/skills/ are outside the projection and "
                f"are being loaded alongside it: {rogue[:5]}"
            )

        status = "FAIL" if problems else "ok"
        failures += bool(problems)
        lines.append(f"{status:4} {s.name}: {len(expected)} skills, "
                     f"{len(list((s.codex / 'agents').glob('*.toml')))} agents")
        lines += [f"       ! {p}" for p in problems]

    return lines, failures


def register_trust(surfaces: list[Surface], check: bool = False) -> list[str]:
    """Codex ignores project-local config/hooks/rules until the project is trusted."""
    config = Path.home() / ".codex" / "config.toml"
    if not config.is_file():
        return ["~/.codex/config.toml not found — is Codex installed?"]
    text = config.read_text(encoding="utf-8")
    missing = [s for s in surfaces if f'[projects."{s.path}"]' not in text]
    if not missing:
        return []
    if check:
        return [f"trust missing: {s.path}" for s in missing]
    backup = config.with_suffix(".toml.pre-codex-sync")
    if not backup.exists():
        backup.write_text(text, encoding="utf-8")
    block = "\n".join(
        f'\n[projects."{s.path}"]\ntrust_level = "trusted"' for s in missing
    )
    config.write_text(text.rstrip("\n") + "\n" + block + "\n", encoding="utf-8")
    return [f"trusted: {s.path}" for s in missing]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", action="append", default=[], help="project one repo (repeatable)")
    ap.add_argument("--all", action="store_true", help="project every surface under ~/GitHub/")
    ap.add_argument("--check", action="store_true", help="report drift, write nothing")
    ap.add_argument("--trust", action="store_true", help="register project trust in ~/.codex/config.toml")
    ap.add_argument("--user", action="store_true", help="project ~/CLAUDE.md onto ~/.codex/AGENTS.md")
    ap.add_argument("--verify", action="store_true", help="ask the codex binary what it actually loads")
    ap.add_argument("--json", action="store_true", help="machine-readable summary")
    ap.add_argument("--briefs", default=None, help=f"per-repo facts for AGENTS.md (default {BRIEFS})")
    args = ap.parse_args()

    if args.repo:
        surfaces = []
        for raw in args.repo:
            p = Path(raw).expanduser().resolve()
            surfaces.append(Surface(name="constellation-root" if p == ROOT else p.name, path=p))
    elif args.all or args.trust or args.verify:
        surfaces = discover()
    elif args.user:
        surfaces = []
    else:
        ap.error("pass --all, --repo PATH, --trust, --user or --verify")

    if args.verify:
        lines, failures = verify(surfaces)
        print("\n".join(lines))
        return 1 if failures else 0

    briefs: dict[str, Any] = {}
    briefs_path = Path(args.briefs).expanduser() if args.briefs else BRIEFS
    if briefs_path.is_file():
        try:
            loaded = json.loads(briefs_path.read_text(encoding="utf-8"))
            briefs = loaded.get("briefs", loaded) if isinstance(loaded, dict) else {}
        except json.JSONDecodeError as exc:
            print(f"warning: {briefs_path} unparseable ({exc}); generating without repo briefs")

    proj = Projection(check=args.check, briefs=briefs)
    done = [proj.run(s) for s in surfaces]

    trust: list[str] = []
    if args.trust:
        trust = register_trust(surfaces, check=args.check)
    if args.user:
        trust += project_user_contract(check=args.check)

    if args.json:
        print(json.dumps({
            "surfaces": [
                {"repo": s.name, "written": s.written, "warnings": s.warnings} for s in done
            ],
            "drift": proj.drift,
            "trust": trust,
        }, indent=2))
        return 1 if (args.check and proj.drift) else 0

    for s in done:
        if s.written or s.warnings:
            print(f"{s.name}: {len(s.written)} written")
            for w in s.warnings:
                print(f"  ! {w}")
    for d in proj.drift:
        print(f"DRIFT {d}")
    for t in trust:
        print(t)
    return 1 if (args.check and proj.drift) else 0


