# Claude pins a model; Codex inherits Omar's global `model` and we translate the
# *intent* (how hard should this agent think) rather than pinning a stale id.
EFFORT_BY_MODEL = {
    "opus": "xhigh",
    "sonnet": "high",
    "haiku": "low",
}
VALID_EFFORT = {"minimal", "low", "medium", "high", "xhigh", "max", "ultra"}

WRITE_TOOLS = {"Write", "Edit", "MultiEdit", "NotebookEdit", "apply_patch"}

# Claude matches on tool name *and* arguments; Codex matches on tool name only
# (regex). Argument-level matchers are preserved by the shim, not by the regex.
TOOL_ALIASES = {
    "Bash": "Bash|shell|exec_command",
    "Write": "Write|apply_patch",
    "Edit": "Edit|apply_patch",
    "MultiEdit": "MultiEdit|apply_patch",
    "NotebookEdit": "NotebookEdit|apply_patch",
    "Task": "Task|agent",
    "WebFetch": "WebFetch|web_fetch",
    "WebSearch": "WebSearch|web_search",
}

_MATCHER_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\((.*)\)$")


def effort_for(meta: dict[str, str]) -> str | None:
    explicit = (meta.get("effort") or "").strip().lower()
    if explicit in VALID_EFFORT:
        return explicit
    model = (meta.get("model") or "").strip().lower()
    for needle, effort in EFFORT_BY_MODEL.items():
        if needle in model:
            return effort
    return None


def sandbox_for(meta: dict[str, str]) -> str | None:
    """A Claude agent with no write tools is a read-only Codex agent."""
    raw = meta.get("tools") or meta.get("allowed-tools")
    if not raw:
        return None
    granted = {t.strip() for t in re.split(r"[,\s]+", raw) if t.strip()}
    if granted & {"*", "all"}:
        return None
    return None if granted & WRITE_TOOLS else "read-only"


def approval_for(meta: dict[str, str]) -> str | None:
    mode = (meta.get("permissionMode") or meta.get("permission-mode") or "").strip()
    return {
        "acceptEdits": "never",
        "bypassPermissions": "never",
        "dontAsk": "never",
        "default": "on-request",
        "plan": "on-request",
    }.get(mode)


def split_matcher(matcher: str | None) -> tuple[str | None, str | None]:
    """`Bash(git commit*)` -> (tool regex, argument glob).

    Codex regexes cannot see tool arguments, so the glob is handed to the shim.
    """
    if not matcher or matcher in {"*", ""}:
        return None, None
    m = _MATCHER_RE.match(matcher.strip())
    if m:
        tool, glob = m.group(1), m.group(2).strip()
        return TOOL_ALIASES.get(tool, tool), (glob or None)
    parts = [p.strip() for p in matcher.split("|") if p.strip()]
    expanded: list[str] = []
    for part in parts:
        expanded.extend(TOOL_ALIASES.get(part, part).split("|"))
    return "|".join(dict.fromkeys(expanded)), None


def deny_to_rule(entry: str) -> str | None:
    """`Bash(git push --force*)` -> a Starlark prefix_rule forbidding it.

    Codex prefix rules match whole argv tokens, so a Claude glob only
    translates exactly when its wildcards are token-trailing. `rm *` and
    `git reset --hard*` translate exactly and stay `forbidden`. A glob whose
    wildcard sits mid-token — `git clean *-fd*` — cannot be expressed, so the
    rule degrades to the shortest safe prefix and downgrades to `prompt`
    rather than silently forbidding a much larger command family.
    """
    m = _MATCHER_RE.match(entry.strip())
    if not m or m.group(1) != "Bash":
        return None

    raw = m.group(2).split()
    tokens: list[str] = []
    exact = True
    for i, token in enumerate(raw):
        last = i == len(raw) - 1
        if token == "*":
            exact = last  # trailing `*` means "then anything" — faithful
            break
        if token.endswith("*") and "*" not in token[:-1]:
            tokens.append(token[:-1])
            exact = last
            break
        if "*" in token:
            exact = False
            break
        tokens.append(token)

    if not tokens:
        return None
    pattern = ", ".join(toml_str(t) for t in tokens)
    decision = "forbidden" if exact else "prompt"
    note = "denied by .claude/settings.json: " + entry
    if not exact:
        note += " (widened to a token prefix; Codex cannot match mid-token globs)"
    return (
        "prefix_rule(\n"
        f"    pattern = [{pattern}],\n"
        f"    decision = {toml_str(decision)},\n"
        f"    justification = {toml_str(note)},\n"
        ")"
    )


