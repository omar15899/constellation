_FM_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n?", re.DOTALL)


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Parse the flat `key: value` frontmatter Claude uses. Lists stay strings."""
    m = _FM_RE.match(text)
    if not m:
        return {}, text
    meta: dict[str, str] = {}
    key: str | None = None
    for raw in m.group(1).splitlines():
        if not raw.strip():
            continue
        if raw[:1] in " \t" and key:  # folded continuation
            meta[key] = f"{meta[key]} {raw.strip()}".strip()
            continue
        if ":" not in raw:
            continue
        key, value = raw.split(":", 1)
        key = key.strip()
        meta[key] = value.strip().strip('"').strip("'")
    return meta, text[m.end():]


def toml_str(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def toml_multiline(value: str) -> str:
    """A TOML multi-line basic string that survives arbitrary Markdown.

    TOML tolerates one or two consecutive quotes inside `\"\"\"…\"\"\"`, so only
    runs of three or more need escaping — which keeps the generated agent
    instructions readable instead of turning every quote into `\\"`. A quote in
    final position would fuse with the terminator, so it is escaped too.
    """
    body = value.replace("\\", "\\\\")
    body = re.sub(r'"{3,}', lambda m: '\\"' * len(m.group()), body)
    if body.endswith('"') and not body.endswith('\\"'):
        body = body[:-1] + '\\"'
    return f'"""\n{body}\n"""'


