#!/usr/bin/env python3
"""Project a repo's `.claude/` control plane into a Codex `.codex/` plane.

The `.claude/` plane is canonical. This script is a deterministic, idempotent
projection onto the Codex CLI's own configuration surface, so that Omar can
drive any repo in the constellation with either Claude Code or Codex and get
the same agents, the same skills, the same guardrails.

Nothing here is bidirectional. In projected repos, edit `.claude/`, re-run this,
commit both. A regular `.codex/profile.json` declaring `mode: native` reserves
the whole Codex surface for its native owner: no output is generated or removed.

Construct mapping (codex-cli 0.146, verified empirically — see
`.claude/docs/codex_parity.md`):

    CLAUDE.md                       ->  AGENTS.md                  (generated)
    .claude/agents/<n>.md           ->  .codex/agents/<n>.toml     (generated)
    .claude/skills/<n>/             ->  .codex/skills/<n>          (symlink)
    .claude/commands/<n>.md         ->  .codex/skills/<n>/SKILL.md (generated)
    .claude/settings.json  hooks    ->  .codex/hooks.json          (generated)
    .claude/settings.json  perms    ->  .codex/config.toml         (generated)
    .claude/settings.json  deny     ->  .codex/rules/default.rules (generated)
    .claude/hooks/*.py|sh           ->  reused in place, never copied

Codex has no custom-slash-command surface in 0.146, so `.claude/commands/`
projects onto skills, which Codex invokes with `$name` instead of `/name`.

Everything written carries a generated banner and is listed in
`.codex/MANIFEST.json`. `--check` recomputes the projection and reports drift
without touching the tree. Hand-written Codex-only material belongs in
`.codex/local/`, which the projection never reads and never removes.
"""

