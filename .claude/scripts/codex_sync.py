@dataclass
class Surface:
    """One repo, one projection."""

    name: str
    path: Path
    written: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def claude(self) -> Path:
        return self.path / ".claude"

    @property
    def codex(self) -> Path:
        return self.path / ".codex"

    def rel(self, p: Path) -> str:
        return str(p.relative_to(self.path))


def native_profile(root: Path) -> bool:
    """Recognise native ownership before reading projection sources or outputs."""
    directory = root / ".codex"
    marker = directory / "profile.json"
    if directory.is_symlink():
        raise ValueError("symlink ancestor of Codex profile: .codex")
    if not os.path.lexists(marker):
        return False
    if marker.is_symlink() or not marker.is_file():
        raise ValueError("Codex profile marker must be a regular local file")
    try:
        profile = json.loads(marker.read_text(encoding="utf-8"))
    except (ValueError, UnicodeError) as exc:
        raise ValueError("invalid Codex profile marker; preserve it before sync") from exc
    if not isinstance(profile, dict) or profile.get("mode") != "native":
        raise ValueError("Codex profile marker must declare mode native")
    return True


def validate_native(s: Surface) -> None:
    """Validate native entry points without assuming a generated manifest/shim."""
    import tomllib

    for rel in ("AGENTS.md", ".codex/config.toml", ".codex/hooks.json"):
        path = s.path / rel
        if not os.path.lexists(path) and rel != "AGENTS.md":
            continue
        if path.is_symlink() or not path.is_file():
            raise ValueError(f"native entry point must be a regular local file: {rel}")
        content = path.read_text(encoding="utf-8")
        if rel == "AGENTS.md":
            if not content.strip():
                raise ValueError("native AGENTS.md must not be empty")
        elif rel.endswith(".toml"):
            tomllib.loads(content)
        else:
            hooks = json.loads(content)
            if (not isinstance(hooks, dict) or set(hooks) - {"description", "hooks"}
                    or not isinstance(hooks.get("hooks"), dict)):
                raise ValueError("invalid native hooks.json structure")
            for groups in hooks["hooks"].values():
                if not isinstance(groups, list):
                    raise ValueError("native hook event must contain a list of groups")
                for group in groups:
                    if not isinstance(group, dict) or not isinstance(group.get("hooks"), list):
                        raise ValueError("native hook group must contain a list of handlers")
                    for handler in group["hooks"]:
                        if (not isinstance(handler, dict) or handler.get("type") != "command"
                                or not isinstance(handler.get("command"), str)
                                or not handler["command"].strip()):
                            raise ValueError("native command hook must declare a command")
                        timeout = handler.get("timeout")
                        if timeout is not None and (isinstance(timeout, bool)
                                or not isinstance(timeout, (int, float)) or timeout <= 0):
                            raise ValueError("native hook timeout must be positive")


MANIFEST_VERSION = 2
NAME_RE = re.compile(r"[a-z0-9][a-z0-9_-]{0,63}\Z")
FIXED_OUTPUTS = {
    "AGENTS.md", ".codex/AGENTS.md", ".codex/README.md", ".codex/config.toml",
    ".codex/hooks.json", ".codex/hook_shim.py", ".codex/rules/default.rules",
}


def valid_name(name: str) -> str:
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise ValueError(f"invalid agent or skill name: {name!r}")
    return name


def managed_path(rel: str, kind: str) -> bool:
    """Ownership is limited to the generator's exact output shapes."""
    if not isinstance(rel, str) or not isinstance(kind, str) or kind not in {"file", "symlink"}:
        return False
    path = PurePosixPath(rel)
    if path.is_absolute() or str(path) != rel or ".." in path.parts:
        return False
    if rel in FIXED_OUTPUTS:
        return kind == "file"
    parts = path.parts
    if len(parts) == 3 and parts[:2] == (".codex", "agents"):
        return kind == "file" and parts[2].endswith(".toml") and bool(NAME_RE.fullmatch(parts[2][:-5]))
    if len(parts) >= 3 and parts[:2] == (".codex", "skills") and NAME_RE.fullmatch(parts[2]):
        return (len(parts) == 3 and kind == "symlink") or (len(parts) == 4 and parts[3] == "SKILL.md" and kind == "file")
    return False


def fingerprint(path: Path) -> dict[str, str] | None:
    """Inspect the directory entry itself, never the target of a symlink."""
    if path.is_symlink():
        return {"kind": "symlink", "target": os.readlink(path)}
    if path.is_file():
        return {"kind": "file", "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    if path.exists():
        return {"kind": "directory" if path.is_dir() else "other"}
    return None


def validate_ownership(raw: Any) -> dict[str, dict[str, str]]:
    if not isinstance(raw, dict):
        raise ValueError("manifest managed_outputs must be an object")
    for rel, entry in raw.items():
        if not isinstance(entry, dict) or not managed_path(rel, entry.get("kind")):
            raise ValueError(f"invalid managed output: {rel!r}")
        if entry["kind"] == "file":
            if set(entry) != {"kind", "sha256"} or not re.fullmatch(r"[0-9a-f]{64}", str(entry.get("sha256", ""))):
                raise ValueError(f"invalid file fingerprint: {rel}")
        elif set(entry) != {"kind", "target"} or entry.get("target") != f"../../.claude/skills/{PurePosixPath(rel).name}":
            raise ValueError(f"invalid skill symlink destination: {rel}")
    for rel in raw:
        if any(str(parent) in raw for parent in PurePosixPath(rel).parents):
            raise ValueError(f"overlapping managed outputs: {rel}")
    return raw


def rebase_links(body: str, source: Path, target: Path) -> str:
    """Keep local Markdown destinations attached to their canonical files."""
    def destination(raw: str) -> str:
        wrapped = raw.startswith("<") and raw.endswith(">")
        value = raw[1:-1] if wrapped else raw
        url = urlsplit(value)
        if not url.path or url.scheme or url.netloc or url.path.startswith(("/", "~")):
            return raw
        absolute = os.path.abspath(source.parent / url.path)
        rebased = os.path.relpath(absolute, target.parent)
        value = urlunsplit(("", "", rebased, url.query, url.fragment))
        return f"<{value}>" if wrapped else value

    # Current canonical documents use ordinary inline links and reference links.
    body = re.sub(r"(\]\()(<[^>]+>|[^\s)]+)([ \t]+[\"'][^\n]*?[\"'])?(\))",
                  lambda m: m[1] + destination(m[2]) + (m[3] or "") + m[4], body)
    return re.sub(r"(?m)^(\s*\[[^]\n]+\]:[ \t]*)(<[^>]+>|\S+)",
                  lambda m: m[1] + destination(m[2]), body)


@dataclass(frozen=True)
class Output:
    kind: str
    value: str
    executable: bool = False

    def fingerprint(self) -> dict[str, str]:
        if self.kind == "symlink":
            return {"kind": "symlink", "target": self.value}
        return {"kind": "file", "sha256": hashlib.sha256(self.value.encode("utf-8")).hexdigest()}


class Projection:
    def __init__(self, check: bool = False, briefs: dict[str, Any] | None = None,
                 legacy_ownership: dict[str, Any] | None = None):
        self.check = check
        self.briefs = briefs or {}
        self.drift: list[str] = []
        self.planned: dict[str, Output] = {}
        # A one-time, externally captured baseline can migrate an old manifest
        # after sources change. Every current output must still match its hash.
        self.legacy_ownership = legacy_ownership

    # -- plan first; no helper writes while source validation is incomplete --

    def write(self, surface: Surface, target: Path, content: str, executable: bool = False) -> None:
        self._plan(surface, target, Output("file", content, executable))

    def symlink(self, surface: Surface, target: Path, dest: str) -> None:
        self._plan(surface, target, Output("symlink", dest))

    def _plan(self, surface: Surface, target: Path, output: Output) -> None:
        rel = surface.rel(target)
        if rel != ".codex/MANIFEST.json" and not managed_path(rel, output.kind):
            raise ValueError(f"invalid projection output: {rel}")
        if rel != ".codex/MANIFEST.json":
            validate_ownership({rel: output.fingerprint()})
        if rel in self.planned:
            raise ValueError(f"duplicate projection output: {rel}")
        self.planned[rel] = output

    @staticmethod
    def _ancestors(s: Surface, rel: str, removable: set[str] | None = None) -> None:
        for parent in (s.path / rel).parents:
            if parent == s.path:
                return
            relative = s.rel(parent)
            if parent.is_symlink() and relative not in (removable or set()):
                raise ValueError(f"symlink ancestor of managed output: {relative}")
            if parent.exists() and not parent.is_dir() and relative not in (removable or set()):
                raise ValueError(f"non-directory ancestor of managed output: {relative}")
        raise ValueError(f"output escapes repository: {rel}")

    def _previous(self, s: Surface) -> dict[str, dict[str, str]]:
        self._ancestors(s, ".codex/MANIFEST.json")
        path = s.codex / "MANIFEST.json"
        if path.is_symlink():
            raise ValueError("manifest must not be a symlink")
        if not path.exists():
            return {}
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict) or data.get("_generated_by") != BANNER or data.get("repo") != s.name:
            raise ValueError("manifest ownership or repository does not match")
        version = data.get("version", 1)
        if version == MANIFEST_VERSION:
            return validate_ownership(data.get("managed_outputs"))
        if version != 1:
            raise ValueError(f"unsupported manifest version: {version}")
        candidates = {rel for rel in FIXED_OUTPUTS if (s.path / rel).exists() or (s.path / rel).is_symlink()}
        for key, prefix, suffix in [("agents", ".codex/agents/", ".toml"),
                                    ("skills", ".codex/skills/", ""),
                                    ("command_skills", ".codex/skills/", "/SKILL.md")]:
            names = data.get(key, [])
            if not isinstance(names, list) or len(names) != len(set(names)):
                raise ValueError(f"invalid legacy manifest {key}")
            candidates.update(prefix + valid_name(name) + suffix for name in names)
        baseline: dict[str, dict[str, str]] = {}
        if self.legacy_ownership is not None:
            if self.legacy_ownership.get("repo_path") != str(s.path):
                raise ValueError("legacy baseline belongs to another repository")
            baseline = validate_ownership({rel: value for rel, value in
                self.legacy_ownership.get("verified_outputs", {}).items() if rel != ".codex/MANIFEST.json"})
            if set(baseline) != candidates:
                raise ValueError("legacy baseline does not cover exactly the previous managed outputs")
        previous = {}
        for rel in sorted(candidates):
            self._ancestors(s, rel)
            current = fingerprint(s.path / rel)
            planned = self.planned[rel].fingerprint() if rel in self.planned else None
            expected = baseline.get(rel) or planned
            if current is not None and current != expected and current != planned:
                raise ValueError(f"cannot safely adopt legacy output {rel}; preserve it or provide a verified pre-change baseline")
            if current is not None:
                previous[rel] = current
        return previous

    def apply(self, s: Surface) -> None:
        """Preflight ownership and all collisions before mutating any output."""
        if native_profile(s.path):
            validate_native(s)
            s.skipped.append("native Codex profile preserved; no projection applied")
            return
        previous = self._previous(s)
        desired = {rel: output for rel, output in self.planned.items() if rel != ".codex/MANIFEST.json"}
        retired = set(previous) - set(desired)
        discovered: set[str] = set()
        for directory in (s.codex / "agents", s.codex / "skills"):
            if directory.is_symlink():
                s.warnings.append(f"unmanaged discovery directory preserved: {s.rel(directory)}")
                continue
            if not directory.is_dir():
                continue
            for entry in directory.iterdir():
                if directory.name == "agents" and entry.suffix == ".toml":
                    discovered.add(s.rel(entry))
                elif directory.name == "skills":
                    if entry.is_symlink():
                        discovered.add(s.rel(entry))
                    elif entry.is_dir() and (entry / "SKILL.md").exists():
                        discovered.add(s.rel(entry / "SKILL.md"))
        for rel in sorted(discovered - set(previous) - set(desired)):
            s.warnings.append(f"unmanaged Codex entry preserved; review separately: {rel}")
        changes: list[str] = []
        for rel in sorted(set(previous) | set(desired)):
            self._ancestors(s, rel, retired)
            # A managed retiring skill symlink may become a generated directory.
            # Do not inspect its descendant through the still-existing symlink.
            under_retired = any(s.rel(parent) in retired and parent.is_symlink()
                                for parent in (s.path / rel).parents if parent != s.path and s.path in parent.parents)
            current = None if under_retired else fingerprint(s.path / rel)
            if (rel in previous and current is not None and current != previous[rel]
                    and (rel not in desired or current != desired[rel].fingerprint())):
                raise ValueError(f"managed output changed locally: {rel}; preserve or reconcile it before sync")
            if rel in desired:
                output = desired[rel]
                if current is not None and rel not in previous and current != output.fingerprint():
                    # A command skill directory can become a shared skill only
                    # when its sole remaining file is a retiring managed SKILL.md.
                    child = rel + "/SKILL.md"
                    removable_directory = (current.get("kind") == "directory" and child in retired
                        and set((s.path / rel).iterdir()) == {s.path / child})
                    if not removable_directory:
                        raise ValueError(f"unmanaged output collision: {rel}")
                if current != output.fingerprint() or (output.executable and current and not (s.path / rel).stat().st_mode & stat.S_IXUSR):
                    changes.append(rel)
            elif current is not None:
                changes.append(rel)
        manifest = self.planned.get(".codex/MANIFEST.json")
        if manifest is not None and fingerprint(s.codex / "MANIFEST.json") != manifest.fingerprint():
            changes.append(".codex/MANIFEST.json")
        if self.check:
            self.drift.extend(f"{s.name}: {rel} would {'remove' if rel in retired else 'change'}" for rel in changes)
            return
        for rel in sorted(retired, key=lambda value: (-value.count("/"), value)):
            target = s.path / rel
            if target.is_symlink() or target.is_file():
                target.unlink()
                s.written.append(f"{rel} (removed)")
            # Empty directories only; extra user files are preserved.
            if rel.endswith("/SKILL.md") and target.parent.is_dir():
                try:
                    target.parent.rmdir()
                except OSError:
                    pass
        for rel in changes:
            if rel in retired:
                continue
            output = self.planned[rel]
            target = s.path / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            if output.kind == "symlink":
                if target.is_dir() and not target.is_symlink():
                    target.rmdir()
                elif target.is_symlink() or target.exists():
                    target.unlink()
                target.symlink_to(output.value)
            else:
                # Replacing the directory entry also preserves any external hard
                # link to the previous inode; an in-place write would not.
                mode = stat.S_IMODE(target.lstat().st_mode) if target.is_file() and not target.is_symlink() else 0o644
                temporary: Path | None = None
                try:
                    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=target.parent,
                                                     prefix=f".{target.name}.", delete=False) as handle:
                        temporary = Path(handle.name)
                        handle.write(output.value)
                    temporary.chmod(0o755 if output.executable else mode)
                    temporary.replace(target)
                finally:
                    if temporary is not None and temporary.exists():
                        temporary.unlink()
            s.written.append(rel)

    # -- agents -------------------------------------------------------------

    def project_agents(self, s: Surface) -> list[str]:
        src_dir = s.claude / "agents"
