    # -- driver --------------------------------------------------------------

    def run(self, s: Surface) -> Surface:
        self.planned = {}
        if native_profile(s.path):
            validate_native(s)
            s.skipped.append("native Codex profile preserved; no projection generated")
            return s
        settings: dict[str, Any] = {}
        settings_path = s.claude / "settings.json"
        if settings_path.is_file():
            settings = json.loads(settings_path.read_text(encoding="utf-8"))
            if not isinstance(settings, dict):
                raise ValueError("settings.json must be an object; no projection was written")

        agents = self.project_agents(s)
        skills = self.project_skills(s)
        commands = self.project_commands(s, skills)
        hooks = self.project_hooks(s, settings)
        if s.claude.is_dir():
            self.project_config(s, settings, agents)

        deny = (settings.get("permissions") or {}).get("deny") or []
        counts = {
            "agents": len(agents),
            "skills": len(skills),
            "commands": len(commands),
            "hook_events": len(hooks),
            "rules": len([d for d in deny if isinstance(d, str) and deny_to_rule(d)]),
        }
        names = {"agents": agents, "skills": skills, "commands": commands}
        if s.claude.is_dir():
            self.project_readme(s, counts)
        self.project_agents_md(s, counts, names)
        if s.claude.is_dir():
            self.project_manifest(s, counts, names)
        self.apply(s)
        return s


