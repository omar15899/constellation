def clean(text: str) -> str:
    """Undo the JSON-escaped quotes that survive a structured agent response."""
    return text.replace('\\"', '"').replace("\\'", "'")


def trim(items: Iterable[Any], cap: int) -> tuple[list[str], int]:
    """Cap a brief section, shortening over-long entries at a word boundary."""
    kept: list[str] = []
    total = 0
    for total, raw in enumerate(items, 1):
        if len(kept) >= cap:
            continue
        text = clean(" ".join(str(raw).split()))
        if len(text) > ENTRY_MAX_CHARS:
            text = text[:ENTRY_MAX_CHARS].rsplit(" ", 1)[0] + " …"
        kept.append(text)
    return kept, max(0, total - len(kept))

