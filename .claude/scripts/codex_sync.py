    # -- skills (from Claude skills, by symlink) -----------------------------

    def project_skills(self, s: Surface) -> list[str]:
        src_dir = s.claude / "skills"
        if not src_dir.is_dir():
            return []
        names: list[str] = []
        for src in sorted(p for p in src_dir.iterdir() if p.is_dir()):
            if src.name.startswith("."):
                continue
            valid_name(src.name)
            skill_md = src / "SKILL.md"
            if not skill_md.is_file():
                s.warnings.append(f"skill {src.name}: no SKILL.md, skipped")
                continue
            meta, _ = split_frontmatter(skill_md.read_text(encoding="utf-8", errors="replace"))
            if not (meta.get("name") and meta.get("description")):
                raise ValueError(f"skill {src.name}: SKILL.md requires name and description")
            if meta.get("name") != src.name:
                raise ValueError(f"skill {src.name}: declared name must match its directory")
            self.symlink(s, s.codex / "skills" / src.name, f"../../.claude/skills/{src.name}")
            names.append(src.name)
        return names

    # -- skills (from Claude slash commands, by generation) ------------------

    def project_commands(self, s: Surface, taken: Iterable[str]) -> list[str]:
        src_dir = s.claude / "commands"
        if not src_dir.is_dir():
            return []
        taken = set(taken)
        command_names: set[str] = set()
        names: list[str] = []
        for src in sorted(src_dir.glob("*.md")):
            if src.stem.upper() in DOC_STEMS:
                continue  # documentation about the commands, not a command
            text = src.read_text(encoding="utf-8", errors="replace")
            meta, body = split_frontmatter(text)
            base = valid_name(meta.get("name") or src.stem)
            if base in command_names:
                raise ValueError(f"duplicate command name: {base}")
            command_names.add(base)
            name = base
            if name in taken:
                name = f"cmd-{base}"
                s.warnings.append(
                    f"command {base}: name taken by a skill, exposed to Codex as ${name}"
                )
            if name in taken:
                raise ValueError(f"duplicate command skill name: {name}")
            valid_name(name)
            taken.add(name)

            description = meta.get("description", "").strip()
            if not description:
                first = next((ln.strip() for ln in body.splitlines() if ln.strip()), base)
                description = re.sub(r"^#+\s*", "", first)[:400]
            hint = meta.get("argument-hint", "").strip()
            usage = f"`${name}{' ' + hint if hint else ''}`"

            header = (
                "---\n"
                f"name: {name}\n"
                f"description: {json.dumps(description)}\n"
                "---\n\n"
                f"<!-- {BANNER} -->\n"
                f"<!-- {CANONICAL.format(src=f'.claude/commands/{src.name}')} -->\n\n"
                f"> Claude Code exposes this as the slash command `/{base}`.\n"
                f"> Codex 0.146 has no custom slash commands, so it is a skill here: {usage}.\n"
                f"> Arguments the user typed after the invocation are the skill's input;\n"
                f"> `$ARGUMENTS`, `$1`, `$2` below refer to them.\n\n"
                "---\n\n"
            )
            self.write(s, s.codex / "skills" / name / "SKILL.md", header + rebase_links(body.strip(), src, s.codex / "skills" / name / "SKILL.md") + "\n")
            names.append(name)
        return names

    # -- hooks ---------------------------------------------------------------

    def project_hooks(self, s: Surface, settings: dict[str, Any]) -> dict[str, Any]:
        hooks = settings.get("hooks") or {}
        if not hooks:
            return {}

        shim = s.codex / "hook_shim.py"
        self.write(s, shim, HOOK_SHIM, executable=True)

        out: dict[str, list[dict[str, Any]]] = {}
        for event, groups in hooks.items():
            projected: list[dict[str, Any]] = []
            for group in groups or []:
                tool_re, glob = split_matcher(group.get("matcher"))
                entries: list[dict[str, Any]] = []
                for hook in group.get("hooks") or []:
                    if hook.get("type") != "command":
                        s.warnings.append(f"hook {event}: non-command type dropped")
                        continue
                    timeout = hook.get("timeout", 15)
                    if isinstance(timeout, bool) or not isinstance(timeout, (int, float)) or not 0 < timeout <= 600:
                        raise ValueError(f"hook {event}: timeout must be in (0, 600] seconds")
                    argv = ["python3", str(shim), "--project-dir", str(s.path),
                            "--timeout", str(max(0.1, timeout - min(2, timeout / 2)))]
                    if glob:
                        argv += ["--command-glob", glob]
                    # The inner shell expands project variables after the
                    # adapter exports them. Quote argv once, including globs.
                    argv += ["--", "sh", "-c", str(hook["command"])]
                    entry: dict[str, Any] = {"type": "command", "command": shlex.join(argv), "timeout": timeout}
                    entries.append(entry)
                if not entries:
                    continue
                block: dict[str, Any] = {"hooks": entries}
                if tool_re:
                    block["matcher"] = tool_re
                projected.append(block)
            if projected:
                out[event] = projected

        if not out:
            return {}
        payload = {
            "description": f"{BANNER}. {CANONICAL.format(src='.claude/settings.json')}.",
            "hooks": out,
        }
        self.write(s, s.codex / "hooks.json", json.dumps(payload, indent=2) + "\n")
        return out

