#!/usr/bin/env python3
"""Filter the task ledger index and print matching tasks.

Reads Ledger/_index.json (generated by aggregate.py).

Filters (all optional, AND-combined):
    --status       open|done|cancelled|rolled_over|blocked|waiting
    --priority     P0|P1|P2|P3
    --project      slug
    --tag          repeatable; each --tag narrows further
    --since        YYYY-MM-DD (by `when`, inclusive)
    --until        YYYY-MM-DD (by `when`, inclusive)
    --has-body     only tasks with non-null body
    --id-prefix    e.g. 2026-04- for all April 2026 ids

Output format: --format markdown (default) | json

Example:
    python3 query_tasks.py --status open --priority P0 --since 2026-04-01
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import sys
from pathlib import Path

VAULT_ROOT = Path(os.environ.get("OMAROS_ROOT", Path("/Users/omarkhalil/OmarOS")))
INDEX = VAULT_ROOT / "02_Tasks_and_Execution" / "Ledger" / "_index.json"


def _parse_date(s: str | None) -> dt.date | None:
    if not s:
        return None
    return dt.date.fromisoformat(s)


def _date_of(t: dict) -> dt.date | None:
    w = t.get("when")
    if not w:
        return None
    try:
        return dt.date.fromisoformat(w)
    except ValueError:
        return None


def _markdown(tasks: list[dict]) -> str:
    if not tasks:
        return "_no matches_\n"
    lines = [
        "| when | time | status | pri | title | project | tags | min | id |",
        "|------|------|--------|-----|-------|---------|------|-----|----|",
    ]
    for t in tasks:
        tags = ", ".join(t.get("tags") or []) or "—"
        lines.append(
            f"| {t.get('when') or '—'} "
            f"| {t.get('time_of_day') or '—'} "
            f"| {t.get('status') or '—'} "
            f"| {t.get('priority') or '—'} "
            f"| {t.get('title') or '—'} "
            f"| {t.get('project') or '—'} "
            f"| {tags} "
            f"| {t.get('duration_min') or '—'} "
            f"| `{t.get('id','')}` |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--status")
    ap.add_argument("--priority")
    ap.add_argument("--project")
    ap.add_argument("--tag", action="append", default=[])
    ap.add_argument("--since")
    ap.add_argument("--until")
    ap.add_argument("--has-body", action="store_true")
    ap.add_argument("--id-prefix")
    ap.add_argument("--format", choices=["markdown", "json"], default="markdown")
    args = ap.parse_args()

    if not INDEX.exists():
        sys.stderr.write(f"error: {INDEX} not found; run aggregate.py first\n")
        sys.exit(4)
    items = json.loads(INDEX.read_text(encoding="utf-8"))

    since = _parse_date(args.since)
    until = _parse_date(args.until)
    tag_set = set(args.tag)

    out = []
    for t in items:
        if args.status and t.get("status") != args.status:
            continue
        if args.priority and t.get("priority") != args.priority:
            continue
        if args.project and t.get("project") != args.project:
            continue
        if tag_set and not tag_set.issubset(set(t.get("tags") or [])):
            continue
        if args.has_body and not t.get("body"):
            continue
        if args.id_prefix and not (t.get("id") or "").startswith(args.id_prefix):
            continue
        if since or until:
            d = _date_of(t)
            if d is None:
                continue
            if since and d < since:
                continue
            if until and d > until:
                continue
        out.append(t)

    # Sort: by when asc, priority asc, id asc
    pri_rank = {"P0": 0, "P1": 1, "P2": 2, "P3": 3, None: 4}
    out.sort(key=lambda t: (
        t.get("when") or "9999-99-99",
        pri_rank.get(t.get("priority")),
        t.get("id") or "",
    ))

    if args.format == "json":
        print(json.dumps(out, indent=2, ensure_ascii=False))
    else:
        print(_markdown(out))


if __name__ == "__main__":
    main()
