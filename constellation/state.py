def engie_learning_path(name: str) -> bool:
    """Recognize the exact topic and daily destinations generated by capture."""
    relative = name.removeprefix(ENGIE_PRIVATE.as_posix() + "/")
    if relative == name:
        return False
    if re.fullmatch(r"Topics/[a-z][a-z0-9]*(?:_[a-z0-9]+)*\.md", relative):
        return len(PurePosixPath(relative).stem) <= 100
    if relative == "Daily/unknown.md":
        return True
    dated = re.fullmatch(r"Daily/([0-9]{4})/([0-9]{4}-[0-9]{2}-[0-9]{2})\.md", relative)
    if dated is None or not dated[2].startswith(dated[1]):
        return False
    try:
        date.fromisoformat(dated[2])
    except ValueError:
        return False
    return True


