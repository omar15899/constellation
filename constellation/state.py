def _require_ignored_untracked(root: Path, paths: Sequence[str]) -> None:
    """Check exact capture or ledger paths against Git without opening their blobs."""
    from .git import GitError, _run

    protected = {name.rstrip("/").casefold() for name in paths}
    descendants = tuple(name + "/" for name in protected)
    ancestors = {parent.as_posix() for name in protected for parent in PurePosixPath(name).parents}
    names = [path.encode("ascii") for path in paths]
    # check-ignore does not support the GIT_LITERAL_PATHSPECS used by _run.
    env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    try:
        # ls-tree does not support icase pathspecs. Compare Git's literal names
        # from both snapshots, including aliases of a directory that contains state.
        for command in (("ls-files", "--cached", "-z"), ("ls-tree", "-r", "--name-only", "-z", "HEAD")):
            recorded = _run(root, *command, timeout=30).decode("utf-8", "surrogateescape")
            for name in recorded.split("\0"):
                folded = name.casefold()
                if folded in protected or folded in ancestors or folded.startswith(descendants):
                    raise StateError("ENGIE learning paths must be untracked, including case aliases")
        result = subprocess.run([git_executable(project=root), "-C", str(root), "check-ignore",
                                 "--no-index", "--stdin", "-z"],
                                input=b"\0".join(names) + b"\0", capture_output=True,
                                env=env, timeout=30, check=False)
    except (GitError, subprocess.SubprocessError) as error:
        raise StateError("ENGIE learning Git privacy could not be verified") from error
    if result.returncode != 0 or result.stdout.split(b"\0")[:-1] != names:
        raise StateError("ENGIE learning paths must be ignored by Git")


def _require_exact_entry(parent: Path | int, name: str) -> None:
    if name not in os.listdir(parent):
        raise StateError("ENGIE learning paths must use the exact filesystem spelling")


def validate_engie_scope(root: Path, paths: Sequence[str]) -> None:
    """Recheck Git privacy and exact regular note paths after resolving their owner."""
    for name in paths:
        if not engie_learning_path(name):
            raise StateError("ENGIE learning requires exact private topic and daily notes")
        path = root / name
        component = root
        for part in PurePosixPath(name).parts:
            component /= part
            try:
                info = component.lstat()
            except FileNotFoundError:
                break
            _require_exact_entry(component.parent, part)
            if component == path:
                if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                    raise StateError("ENGIE learning notes must be singly linked regular files")
            elif not stat.S_ISDIR(info.st_mode):
                raise StateError("ENGIE learning notes must have real parent directories")
    _require_ignored_untracked(root, paths)


def now() -> str:
    """Return an unambiguous UTC timestamp for curated evidence."""
    return datetime.now(timezone.utc).isoformat()


def digest(value: Any) -> str:
    """Hash deterministic JSON, preserving exact Unicode string values."""
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                     ensure_ascii=False).encode()).hexdigest()


def git(root: Path, *args: str) -> str:
    """Run bounded, read-only Git plumbing without persisting process output."""
    from .git import GitError, _text
    try:
        return _text(root, *args, timeout=30)
    except GitError as error:
        raise StateError("Git metadata could not be read") from error


def validate_paths(root: Path, assignments: Mapping[str, str],
                   policy: Mapping[str, Any] | None = None) -> dict[str, str]:
    """Validate exact ownership and explicit publication path capabilities.

    Args:
        root: Canonical Git worktree root.
        assignments: Exact relative file paths mapped to native author IDs.
        policy: Optional exact path lists for adopting staging, removing index
            entries, and publishing leaf symbolic links. A removal concerns
            only this owner's Git tree; its worktree path is never followed.

    Returns:
        A sorted copy of the validated assignment map.

    Raises:
        StateError: A path or capability is ambiguous, traverses an undeclared
            link, or leaves this Git owner.
    """
    if not isinstance(assignments, Mapping) or not assignments:
        raise StateError("A change requires at least one exact file path")
    if policy is not None and not isinstance(policy, Mapping):
        raise StateError("Publication policy must be an object")
    if Path(git(root, "rev-parse", "--show-toplevel")).resolve() != root:
        raise StateError("Root must be the exact Git owner")
    folded: dict[str, str] = {}
    for value, author in assignments.items():
        if not isinstance(value, str):
            raise StateError("Assignments require literal relative file paths")
        path = PurePosixPath(value)
        if (not isinstance(author, str) or not author.strip() or not value
                or path.is_absolute() or str(path) != value or "\\" in value
                or any(part.casefold() in {"..", ".", ".git"} for part in path.parts)
                or any(ord(character) < 32 for character in value)):
            raise StateError("Assignments require literal relative file paths and author IDs")
        if IS_WINDOWS:
            try:
                validate_windows_relative(value)
            except ValueError as error:
                raise StateError(str(error)) from error
        if value.casefold() in folded:
            raise StateError("Case aliases cannot have separate owners")
        folded[value.casefold()] = value

    capabilities: dict[str, set[str]] = {}
    for option in PUBLICATION_PATH_OPTIONS:
        declared = (policy or {}).get(option, [])
        if (not isinstance(declared, list)
                or any(not isinstance(name, str) for name in declared)
                or len(declared) != len(set(declared))
                or not set(declared).issubset(assignments)):
            raise StateError(f"{option} must list distinct exact owned paths")
        capabilities[option] = set(declared)
    removals = capabilities["remove_paths"]
    symlinks = capabilities["symlink_paths"]
    if removals & symlinks:
        raise StateError("A path cannot be both removed and published as a link")

    owner_by_parent: dict[Path, Path] = {}
    for value in assignments:
        path = PurePosixPath(value)
        for ancestor in path.parents:
            ancestor_name = folded.get(ancestor.as_posix().casefold())
            if ancestor_name is not None and not (
                    ancestor_name in symlinks and value in removals):
                raise StateError("Only explicit link replacements may remove scoped descendants")
        # Removal operates on this owner's index, even when an old tracked tree
        # has become a symlink locally. Task creation verifies tracked ownership;
        # later snapshots must also work after those entries have been removed.
        if value in removals:
            continue
        if IS_WINDOWS:
            validate_windows_lookup(root / value, allow_leaf_symlink=value in symlinks)
        current = root
        for part in path.parts:
            current /= part
            if is_reparse(current) and (current != root / value or value not in symlinks
                                        or not current.is_symlink()):
                raise StateError("Scope cannot traverse symbolic links or reparse points")
        if not current.is_symlink():
            if current.is_dir():
                raise StateError("Scope contains a directory; enumerate exact files")
            if current.exists():
                metadata = current.stat()
                if not stat.S_ISREG(metadata.st_mode) or (IS_WINDOWS and metadata.st_nlink != 1):
                    raise StateError("Scope requires unaliased regular files, declared links or deletions")
        parent = current.parent
        while not parent.exists():
            parent = parent.parent
        if parent not in owner_by_parent:
            owner_by_parent[parent] = Path(git(parent, "rev-parse", "--show-toplevel")).resolve()
        if owner_by_parent[parent] != root:
            raise StateError("Scope crosses a different Git owner")
    names = sorted(assignments)
    return {name: assignments[name] for name in names}


def effective_policy(root: str | Path, supplied: Mapping[str, Any] | None = None, *,
                     engie_learning: bool = False) -> dict[str, Any]:
    """Add current central restrictions and bind the relevant owner instructions.

    Explicit policy cannot remove the project's private patterns or preserved
    Git validators. Exact publication capabilities are validated against the
    owned paths separately. Re-reading this policy for each candidate makes a
    later profile edit invalidate earlier evidence.
    """
    root = Path(root).resolve()
    policy = dict(supplied or {})
    from .projects import load_projects
    selected = (_engie_project() if engie_learning else next(
        (project for project in load_projects(SOURCE) if Path(project["root"]).resolve() == root), None))
    policy["private_patterns"] = sorted(set(policy.get("private_patterns", []))
        | set((selected or {}).get("private_patterns", [])))
    chain = policy.get("preserve_git_hook_chain") or []
    chain = [chain] if isinstance(chain, str) else list(chain)
    configured = (selected or {}).get("preserve_git_hook_chain") or []
    configured = [configured] if isinstance(configured, str) else list(configured)
    policy["preserve_git_hook_chain"] = sorted(set(chain + configured))
    instructions = [root / "AGENTS.md"]
    if selected and selected.get("profile"):
        instructions.append(SOURCE / selected["profile"])
    policy["_profile_sha256"] = digest({"project": selected,
        "instructions": {str(path): hashlib.sha256(path.read_bytes()).hexdigest()
                         for path in instructions if path.is_file()}})
    return policy


def artifact_fingerprint(task: Mapping[str, Any], candidate_value: Any = None) -> str:
    """Bind checks to the candidate Git tree, target, policy and task contract.

    Candidate calculation uses an isolated Git index, so unrelated staged work
    is neither included nor changed. Every call rechecks current file bytes.
    """
    root = Path(task["root"])
    engie_learning = task.get("ledger") == ENGIE_ROUTE
    policy = effective_policy(root, task.get("policy"), engie_learning=engie_learning)
    validate_paths(root, task["assignments"], policy)
    if engie_learning:
        validate_engie_scope(root, task["paths"])
    if task.get("mode", "publish") == "local" and any(
            policy.get(option) for option in PUBLICATION_PATH_OPTIONS):
        raise StateError("Publication path capabilities require publication mode")
    from .git import private_path

    instructions: dict[str, str | None] = {}
    instruction_parents = {root}
    for name in task["paths"]:
        # Bind accessible public ancestor rules even for index-only removals,
        # but never enter a private subtree or follow a replaced skill link.
        parent = root
        for part in PurePosixPath(name).parts[:-1]:
            parent /= part
            if private_path(parent.relative_to(root).as_posix(), policy) or parent.is_symlink():
                break
            instruction_parents.add(parent)
    for parent in sorted(instruction_parents):
        instruction = parent / "AGENTS.md"
        relative_instruction = instruction.relative_to(root).as_posix()
        if private_path(relative_instruction, policy):
            continue
        if instruction.is_symlink() or (instruction.exists() and not instruction.is_file()):
            raise StateError("Applicable instructions must be regular files")
        instructions[relative_instruction] = (
            hashlib.sha256(instruction.read_bytes()).hexdigest() if instruction.exists() else None)
    if task.get("mode", "publish") == "local":
        files = {}
        for name in task["paths"]:
            path = root / name
            files[name] = ({"sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                            "mode": stat.S_IMODE(path.stat().st_mode)}
                           if path.exists() else None)
        candidate_digest = digest({"root": str(root), "files": files, "mode": "local",
                                   "policy": policy})
    else:
        from .git import candidate

        current = candidate_value or candidate(task["root"], task["paths"], task["target"], task.get("policy"))
        candidate_digest = current["fingerprint"]
    contract = {"candidate": candidate_digest,
                "instructions": instructions,
                "requirement": task["requirement"],
                "assignments": task["assignments"],
                "authors": task.get("authors", {path: [author]
                    for path, author in task["assignments"].items()}),
                "assignment_history": task.get("assignment_history", []),
                "actor_sessions": task.get("actor_sessions", {}),
                "actor_session_history": task.get("actor_session_history", {}),
                "coordinator": task["coordinator"],
                "owner_session_id": task.get("session_id", task["coordinator"]),
                "required_checks": task["required_checks"]}
    if "publication_message" in task:
        contract["publication_message"] = task["publication_message"]
    return digest(contract)


def fingerprint(task: Mapping[str, Any], candidate_value: Any = None) -> str:
    """Bind reviews to both the current artifact and latest check evidence.

    Replacing a check command, or rerunning it after review, requires a fresh
    review. Artifact checks use a separate digest to avoid a circular binding.
    """
    return digest({"artifact": artifact_fingerprint(task, candidate_value),
                   "checks": task["checks"]})


def authors(task: Mapping[str, Any]) -> set[str]:
    """Return recorded authors and their current or historical event aliases."""
    return set(task["assignments"].values()) | {
        author for identities in task.get("authors", {}).values() for author in identities} | {
        session for sessions in task.get("actor_session_history", {}).values() for session in sessions
    } | set(task.get("actor_sessions", {}).values())


def _record_actor_sessions(task: dict[str, Any], updates: Mapping[str, str], *,
                           normalize_legacy_uuid: bool = False) -> list[dict[str, str]]:
    """Join explicitly identified native actors to unique hook-event sessions.

    Previous aliases remain reserved to their actor and ineligible for review.
    The owning task session is a routing selector, not inferred actor evidence.
    Only explicit reassignment may normalize an inactive historical raw UUID;
    its caller records the reason and returned corrections in assignment history.
    """
    if not isinstance(updates, Mapping):
        raise StateError("Actor sessions must map native identities to event sessions")
    active = set(task["assignments"].values()) | {task["coordinator"]}
    known = active | {
        author for identities in task.get("authors", {}).values() for author in identities}
    current = dict(task.get("actor_sessions", {}))
    history = {actor: list(sessions) for actor, sessions
               in task.get("actor_session_history", {}).items()}
    previous_aliases = {actor: set(sessions) for actor, sessions in history.items()}
    for actor, session in current.items():
        history.setdefault(actor, []).append(session)
    for actor, session in updates.items():
        if (not isinstance(actor, str) or actor not in known or not isinstance(session, str)
                or not session.strip() or session != session.strip()):
            raise StateError("Session aliases require declared native actors and exact nonempty IDs")
        current[actor] = session
        history.setdefault(actor, []).append(session)
    owners: dict[str, str] = {}
    corrections: dict[str, str] = {}
    for actor, sessions in history.items():
        for session in sessions:
            if session in owners and owners[session] != actor:
                raise StateError("An event session cannot identify distinct native actors")
            if session in known and session != actor:
                legacy_uuid = re.fullmatch(r"[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}", session)
                established = session in previous_aliases.get(actor, set())
                explicit = normalize_legacy_uuid and updates.get(actor) == session
                if session in active or not legacy_uuid or not (established or explicit):
                    raise StateError("An event session cannot identify distinct native actors")
                if not established:
                    corrections[session] = actor
            owners[session] = actor
    task["actor_sessions"] = current
    task["actor_session_history"] = {actor: sorted(set(sessions))
                                      for actor, sessions in history.items()}
    return [{"legacy_actor": legacy, "native_actor": actor}
            for legacy, actor in sorted(corrections.items())]


def ready(task: Mapping[str, Any]) -> str:
    """Require current successful checks and independent approval.

    Returns:
        The current fingerprint, suitable for a publication journal.

    Raises:
        StateError: Evidence is missing, failed, stale or not independent.
    """
    artifact = artifact_fingerprint(task)
    current = digest({"artifact": artifact, "checks": task["checks"]})
    for check_id in task["required_checks"]:
        check = task["checks"].get(check_id, {})
        if (check.get("status") != "passed" or check.get("returncode") != 0
                or check.get("fingerprint") != artifact):
            raise StateError("Required check is missing, failed or stale: " + check_id)
    author_ids = authors(task)
    # The latest report from each reviewer governs; an old approval cannot hide
    # a later rejection, while a corrected re-review remains possible.
    reports = {report["reviewer"]: report for report in task["reviews"]
               if report["fingerprint"] == current}
    independent = [report for reviewer, report in reports.items()
                   if reviewer not in author_ids and reviewer != task["coordinator"]]
    if any(report["verdict"] == "reject" for report in independent):
        raise StateError("A current independent review rejects this candidate")
    if not any(report["verdict"] == "approve" for report in independent):
        raise StateError("Current independent approval is missing")
    return current


def _require_mutable_evidence(task: Mapping[str, Any]) -> None:
    """Freeze evidence for a committed candidate until a verified local follow-up.

    Git owns remote verification and records the explicit pending-local status.
    Requiring its matching verified journal also covers interrupted commits
    whose task record has not yet received the publication receipt.
    """
    if task.get("ledger") == ENGIE_ROUTE:
        return
    from .git import _journal_path

    publication = task.get("publication", {})
    journal_path = _journal_path(task["root"], task["id"])
    if not publication and not journal_path.exists():
        return
    if publication.get("status") == "verified_local_changes" and journal_path.is_file():
        journal = json.loads(read_ledger_record(journal_path))
        if (publication.get("commit") and journal.get("phase") == "verified"
                and journal.get("commit") == publication["commit"]):
            return
    raise StateError("Evidence is frozen by publication; recover the pending commit or push first")


def _write_record(descriptor: int, task: Mapping[str, Any]) -> None:
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        json.dump(task, handle, ensure_ascii=False, sort_keys=True, indent=2)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())


@contextmanager
def _flock(descriptor: int, *, shared: bool) -> Iterator[None]:
    import fcntl

    fcntl.flock(descriptor, fcntl.LOCK_SH if shared else fcntl.LOCK_EX)
    try:
        yield
    finally:
        fcntl.flock(descriptor, fcntl.LOCK_UN)


def require_unowned_paths(root: Path, paths: Iterable[str],
                          tasks: Iterable[Mapping[str, Any]]) -> None:
    """Raise when an unfinished task for the same root overlaps a requested path."""
    incoming = {name.casefold() for name in paths}
    for task in tasks:
        if task["status"] == "closed" or task["root"] != str(root):
            continue
        occupied = {name.casefold() for name in task["paths"]}
        if any(a == b or a.startswith(b + "/") or b.startswith(a + "/")
               for a in incoming for b in occupied):
            raise StateError("Another unfinished task owns part of this scope: " + task["id"])


class Store:
    """A private, atomic JSON ledger with one lock covering ownership changes.

    Args:
        state_dir: Private state root, defaulting to CONSTELLATION_STATE_DIR or
            the local platform state location. Different sessions must share it.
        read_only: Open a snapshot view without creating or chmodding directories.
    """

    def __init__(self, state_dir: str | Path | None = None, *, read_only: bool = False):
        root = Path(state_dir or os.environ.get("CONSTELLATION_STATE_DIR")
                    or default_state_dir()).expanduser()
        self.root = validate_windows_lookup(root) if IS_WINDOWS else root.resolve()
        self.tasks = self.root / "tasks"
        project = _engie_project()
        if project is not None and self.root.is_relative_to(Path(project["root"]) / ENGIE_LEDGER.parent):
            raise StateError("Use --engie-learning to select the private task ledger")
        if not read_only:
            secure_mkdir(self.root)
            secure_mkdir(self.tasks)

    def _path(self, task_id: str) -> Path:
        if not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9_.-]{0,127}", task_id):
            raise StateError("Task ID must be a simple local identifier")
        if IS_WINDOWS:
            validate_windows_relative(task_id + ".json")
        return self.tasks / (task_id + ".json")

    @contextmanager
    def _lock(self) -> Iterator[None]:
        with ledger_lock(self.root / ".lock"):
            yield

    @contextmanager
    def _observe(self, *, required: bool = False) -> Iterator[None]:
        """Share an existing POSIX lock without creating or modifying it."""
        try:
            descriptor = os.open(self.root / ".lock", os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
        except FileNotFoundError:
            if required:
                raise StateError("Local note creation requires an initialized Constellation ledger") from None
            yield
            return
        try:
            metadata = os.fstat(descriptor)
            if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
                raise StateError("The existing task lock must be a regular file")
            with _flock(descriptor, shared=True):
                yield
        finally:
            os.close(descriptor)

    @contextmanager
    def _begin_locked(self, root: Path) -> Iterator[list[dict[str, Any]]]:
        with self._lock():
            private = EngieLearningStore.existing({root})
            if private is None:
                yield []
            else:
                with private._observe():
                    yield private.list_tasks()

    def _names(self) -> list[str]:
        try:
            metadata = self.tasks.lstat()
        except FileNotFoundError:
            return []
        if not stat.S_ISDIR(metadata.st_mode):
            raise StateError("The task directory must be a real directory")
        return sorted(path.stem for path in self.tasks.iterdir() if path.suffix == ".json")

    def _read_text(self, path: Path) -> str:
        return read_ledger_record(path)

    def _read(self, task_id: str) -> dict[str, Any]:
        try:
            task = json.loads(self._read_text(self._path(task_id)))
        except (FileNotFoundError, json.JSONDecodeError) as error:
            raise StateError("Task is absent or unreadable: " + task_id) from error
        if not isinstance(task, dict) or task.get("schema") != 1 or task.get("id") != task_id:
            raise StateError("Unsupported or mismatched task record")
        return task

    def save_locked(self, task: dict[str, Any]) -> None:
        """Durably save while holding locked(); supports publication checkpoints."""
        destination = self._path(task["id"])
        descriptor, temporary = tempfile.mkstemp(prefix=".task-", dir=self.tasks)
        try:
            _write_record(descriptor, task)
            replace_ledger_record(Path(temporary), destination)
        finally:
            if os.path.exists(temporary):
                os.unlink(temporary)

    @contextmanager
    def locked(self, task_id: str) -> Iterator[dict[str, Any]]:
        """Yield the current mutable task and save only on successful completion."""
        with self._lock():
            task = self._read(task_id)
            yield task
            self.save_locked(task)

    def get(self, task_id: str) -> dict[str, Any]:
        """Read one task without changing its lifecycle."""
        with self._lock():
            return self._read(task_id)

    def active(self, root: str | Path | None = None) -> list[dict[str, Any]]:
        """Return unfinished assignments, optionally for one exact Git owner."""
        selected = str(Path(root).resolve()) if root is not None else None
        with self._lock():
            return [task for task in self.list_tasks() if task["status"] != "closed"
                    and (selected is None or task["root"] == selected)]

    def list_tasks(self) -> list[dict[str, Any]]:
        """Read atomic task snapshots without acquiring the publication lock.

        Git hooks may run while their parent holds locked(). Each record is
        atomic, but this intentionally does not promise a global snapshot.
        """
        return [self._read(name) for name in self._names()]

    def begin(self, task_id: str, root: str | Path, requirement: str,
              assignments: Mapping[str, str], *, coordinator: str,
              session_id: str | None = None,
              actor_sessions: Mapping[str, str] | None = None,
              mode: str = "publish",
              remote: str = "origin", branch: str | None = None,
              ref: str | None = None, required_checks: Sequence[str] = ("default",),
              policy: dict[str, Any] | None = None,
              publication_message: str | None = None) -> dict[str, Any]:
        """Freeze scope and publication target before changing files.

        Existing task IDs and overlapping unfinished scopes fail closed. A query
        needs no task; every change records at least one required behavior check.
        An authorized publication message opts a publish task into automatic
        publication after the CLI records a current independent approval.
        """
        root = Path(root).expanduser()
        if IS_WINDOWS:
            validate_windows_lookup(root.absolute())
        root = root.resolve()
        if mode not in {"publish", "local"}:
            raise StateError("Task mode must be publish or local")
        if publication_message is not None:
            if mode != "publish":
                raise StateError("Automatic publication requires publish mode")
            if (not isinstance(publication_message, str) or not publication_message.strip()
                    or "\0" in publication_message):
                raise StateError("Automatic publication requires a nonempty commit message")
        if not requirement.strip() or not coordinator.strip():
            raise StateError("A change needs a requirement and coordinator ID")
        if Path(git(root, "rev-parse", "--show-toplevel")).resolve() != root:
            raise StateError("Root must be the exact Git owner")
        engie_learning = isinstance(self, EngieLearningStore)
        policy = effective_policy(root, policy, engie_learning=engie_learning)
        owners = validate_paths(root, assignments, policy)
        if mode == "local" and any(policy.get(option) for option in PUBLICATION_PATH_OPTIONS):
            raise StateError("Publication path capabilities require publication mode")
        if engie_learning:
            validate_engie_scope(root, list(owners))
        from .git import _run, target as publication_target

        removals = set(policy.get("remove_paths", []))
        if removals:
            # Inspect only Git names. Worktree traversal could follow a replaced
            # skill directory or expose private data that must stay local.
            tracked_names = {
                name.decode("utf-8", "surrogateescape")
                for output in (_run(root, "ls-files", "--cached", "-z"),
                               _run(root, "ls-tree", "-r", "--name-only", "-z", "HEAD"))
                for name in output.split(b"\0") if name}
            if not removals.issubset(tracked_names):
                raise StateError("Index removals must name entries tracked by this Git owner")
        checks = list(required_checks)
        if not checks or len(set(checks)) != len(checks) or not all(checks):
            raise StateError("Declare unique required checks")
        target = publication_target(root, remote, branch, ref) if mode == "publish" else None
        task = {"schema": 1, "id": task_id, "root": str(root),
                "requirement": requirement, "assignments": owners, "paths": list(owners),
                "authors": {path: [author] for path, author in owners.items()},
                "assignment_history": [],
                "coordinator": coordinator, "session_id": session_id or coordinator,
                "target": target, "mode": mode,
                "base_head": git(root, "rev-parse", "HEAD"), "policy": policy,
                "required_checks": checks, "checks": {}, "reviews": [],
                "milestones": [], "publication": {}, "created": now(), "status": "open"}
        if publication_message is not None:
            task["publication_message"] = publication_message
        if engie_learning:
            task["ledger"] = ENGIE_ROUTE
        _record_actor_sessions(task, actor_sessions if actor_sessions is not None else {})
        with self._begin_locked(root) as peers:
            if self._path(task_id).exists():
                raise StateError("Task already exists; resume it instead")
            if any(other["id"].casefold() == task_id.casefold() for other in peers):
                raise StateError("Task ID already exists in the other task ledger; resume it there")
            require_unowned_paths(root, owners, self.list_tasks() + peers)
            self.save_locked(task)
        return task

    def checkpoint(self, task_id: str, summary: str) -> dict[str, Any]:
        """Append a curated milestone; callers must exclude private raw material."""
        if not summary.strip():
            raise StateError("A checkpoint needs a meaningful summary")
        with self.locked(task_id) as task:
            task["milestones"].append({"at": now(), "summary": summary})
        return task

    def assign(self, task_id: str, path: str, author: str, reason: str,
               session_id: str | None = None, owner_session_id: str | None = None) -> dict[str, Any]:
        """Transfer an existing exact path without forgetting previous authors.

        Args:
            task_id: Existing open task, before any publication intent.
            path: Exact path already belonging to this task.
            author: Native agent ID returned by the spawning tool. Environment
                variables may be inherited and do not establish actor identity.
            reason: Curated reason for correcting or transferring ownership.
            session_id: Optional event-session alias explicitly associated with
                this native actor. This is separate from the task's owning session.
                An inactive historical raw UUID may be explicitly normalized;
                it remains an author and cannot already identify another actor.
            owner_session_id: Optional parent session used to group native hook
                events. Corrects routing or resumes this task in another session
                without inferring or changing the actor's identity.

        Returns:
            Updated task; its previous checks and reviews remain as stale history.
        """
        if (not isinstance(path, str) or not isinstance(author, str) or not author.strip()
                or not isinstance(reason, str) or not reason.strip()):
            raise StateError("Reassignment needs a native author ID and a reason")
        if owner_session_id is not None and (not isinstance(owner_session_id, str)
                or not owner_session_id.strip() or owner_session_id != owner_session_id.strip()):
            raise StateError("The owning session requires an exact nonempty native ID")
        with self.locked(task_id) as task:
            from .git import _journal_path

            engie_learning = task.get("ledger") == ENGIE_ROUTE
            if (task["status"] != "open" or task["publication"] or (
                    not engie_learning and _journal_path(task["root"], task_id).exists())):
                raise StateError("Cannot reassign a closed task or a publication in progress")
            if path not in task["assignments"]:
                raise StateError("Reassignment cannot extend the task's declared scope")
            validate_paths(Path(task["root"]), task["assignments"],
                           effective_policy(task["root"], task.get("policy"), engie_learning=engie_learning))
            previous = task["assignments"][path]
            previous_owner_session = task.get("session_id", task["coordinator"])
            if author == previous and (session_id is None
                    or task.get("actor_sessions", {}).get(author) == session_id) and (
                    owner_session_id is None or owner_session_id == previous_owner_session):
                raise StateError("This native author already owns the path")
            history = task.setdefault("authors", {name: [owner]
                for name, owner in task["assignments"].items()})
            history[path] = sorted(set(history.get(path, [])) | {previous, author})
            task["assignments"][path] = author
            corrections = _record_actor_sessions(task,
                {author: session_id} if session_id is not None else {},
                normalize_legacy_uuid=session_id is not None)
            if owner_session_id is not None:
                task["session_id"] = owner_session_id
            task.setdefault("assignment_history", []).append({"at": now(), "path": path,
                "previous": previous, "author": author, "reason": reason, "session_id": session_id,
                "previous_owner_session_id": previous_owner_session,
                "owner_session_id": task.get("session_id", task["coordinator"]),
                "identity_corrections": corrections})
        return task

    def check(self, task_id: str, check_id: str, argv: Sequence[str], *,
              timeout: float = 300) -> dict[str, Any]:
        """Run a bounded check outside the lock and retain its current attempt.

        Raw command/output is not stored. A failed, timed-out, superseded or
        mutating check cannot reuse older successful evidence.
        """
        if isinstance(argv, str) or not argv or not all(isinstance(item, str) and item for item in argv):
            raise StateError("Checks require a nonempty argv, not a shell string")
        if not 0 < timeout <= 3600:
            raise StateError("Check timeout must be within (0, 3600] seconds")
        with self.locked(task_id) as task:
            if check_id not in task["required_checks"] or task["status"] != "open":
                raise StateError("Check is not declared on an open task")
            _require_mutable_evidence(task)
            version = artifact_fingerprint(task)
            attempt = uuid.uuid4().hex
            task["checks"][check_id] = {"attempt": attempt, "status": "running",
                "fingerprint": version, "argv_sha256": digest(list(argv)), "started": now()}
            root = task["root"]
        command = list(argv)
        resolution_error = None
        if IS_WINDOWS:
            project = Path(root)
            try:
                if command[0].casefold() in {"git", "git.exe"}:
                    command[0] = git_executable(project=project)
                else:
                    command[0] = windows_executable(command[0], project=project)
            except (OSError, ValueError) as error:
                resolution_error = error
        code, output, status = None, b"", "failed"
        if resolution_error is None:
            try:
                result = subprocess.run(command, cwd=root, capture_output=True,
                                        timeout=timeout, check=False)
                code, output = result.returncode, result.stdout + result.stderr
                status = "passed" if code == 0 else "failed"
            except (OSError, subprocess.TimeoutExpired):
                pass
        with self.locked(task_id) as task:
            record = task["checks"][check_id]
            if record["attempt"] != attempt:
                raise StateError("A newer check attempt superseded this result")
            try:
                changed = artifact_fingerprint(task) != version
            except (ValueError, RuntimeError):
                changed = True
            record.update(returncode=code, status="stale" if changed else status,
                          output_sha256=hashlib.sha256(output).hexdigest(), finished=now())
        if resolution_error is not None:
            raise StateError(f"Cannot resolve Windows check command: {resolution_error}") from resolution_error
        return record

    def review(self, task_id: str, reviewer: str, evidence: str,
               verdict: str = "approve", *, expected_fingerprint: str) -> dict[str, Any]:
        """Record an independent assessment of an explicitly observed candidate.

        The reviewer must supply the fingerprint obtained before review. This
        prevents a changed artifact being silently relabelled as reviewed.
        """
        if not reviewer.strip() or not evidence.strip() or verdict not in {"approve", "reject"}:
            raise StateError("Review needs an identity, evidence and a supported verdict")
        with self.locked(task_id) as task:
            _require_mutable_evidence(task)
            if reviewer in authors(task) or reviewer == task["coordinator"]:
                raise StateError("Authors and coordinator cannot approve their own change")
            current = fingerprint(task)
            if task["status"] != "open" or expected_fingerprint != current:
                raise StateError("Review candidate changed or task is no longer open")
            report = {"reviewer": reviewer, "evidence": evidence, "verdict": verdict,
                      "fingerprint": current, "at": now()}
            task["reviews"].append(report)
        return report

    def status(self, task_id: str) -> dict[str, Any]:
        """Return task state and independently recomputed readiness."""
        task = self.get(task_id)
        current = None
        try:
            current = fingerprint(task)
            ready(task)
            gate = {"ready": True, "fingerprint": current}
        except (ValueError, RuntimeError) as error:
            gate = {"ready": False, "fingerprint": current, "reason": str(error)}
        return {**task, "gate": gate}

    def finish(self, task_id: str) -> dict[str, Any]:
        """Close reviewed local work without making any Git publication claim."""
        with self.locked(task_id) as task:
            if task.get("mode") != "local" or task["status"] != "open":
                raise StateError("Local finish requires an open local task")
            version = ready(task)
            task["status"] = "closed"
            task["closed"] = {"at": now(), "fingerprint": version, "kind": "local"}
        return task

    def cancel(self, task_id: str, reason: str) -> dict[str, Any]:
        """Cancel an unassessed assignment without claiming completion or editing files.

        A task with checks, reviews or publication intent must be resolved in its
        existing lifecycle; cancellation cannot hide adverse evidence.
        """
        if not reason.strip():
            raise StateError("Cancellation requires an explicit reason")
        with self.locked(task_id) as task:
            if (task["status"] != "open" or task["checks"] or task["reviews"]
                    or task["publication"]):
                raise StateError("Only an open unassessed assignment can be cancelled")
            task["status"] = "closed"
            task["closed"] = {"at": now(), "kind": "cancelled", "reason": reason}
        return task


class EngieLearningStore(Store):
    """Use the ledger bound to the registered vault and its ignored ENGIE area."""

    def __init__(self) -> None:
        from resources.vault import check_profile_binding

        project = _engie_project()
        if os.name != "posix" or project is None:
            raise StateError("ENGIE learning requires a registered POSIX OmarOS vault")
        self.vault = Path(project["root"])
        binding = check_profile_binding(SOURCE / "profiles/projects.json", str(self.vault))
        self.owner = tuple(binding["owner"])
        self.root = self.vault / ENGIE_LEDGER
        self.tasks = self.root / "tasks"
        with self._directory(tasks=True):
            pass
        _require_ignored_untracked(self.vault, [f"{ENGIE_LEDGER}/", f"{ENGIE_LEDGER}/tasks/",
                                               f"{ENGIE_LEDGER}/.lock"])

    @classmethod
    def existing(cls, roots: set[Path] | None = None) -> EngieLearningStore | None:
        """Find the fixed ledger, without creating it or accepting alternate paths."""
        project = _engie_project()
        if os.name != "posix" or project is None:
            return None
        vault = Path(project["root"])
        if roots is not None and vault not in roots:
            return None
        try:
            (vault / ENGIE_LEDGER).lstat()
        except FileNotFoundError:
            return None
        return cls()

    @staticmethod
    def _private_entry(descriptor: int, *, directory: bool) -> None:
        info = os.fstat(descriptor)
        correct_type = (stat.S_ISDIR(info.st_mode) if directory else
                        stat.S_ISREG(info.st_mode) and info.st_nlink == 1)
        if not correct_type or info.st_uid != os.geteuid() or info.st_mode & 0o077:
            raise StateError("ENGIE ledger directories and files must be private and owner-controlled")

    def _require_vault_owner(self, path: Path, directory: int) -> None:
        """Reject a nested worktree or bare Git directory at an opened ancestor."""
        try:
            os.stat(".git", dir_fd=directory, follow_symlinks=False)
        except FileNotFoundError:
            pass
        else:
            raise StateError("The ENGIE task ledger must stay inside the registered Git owner")
        # Git also discovers a bare repository without a .git entry. Its HEAD
        # is required, so only that case needs a fresh Git owner query.
        try:
            os.stat("HEAD", dir_fd=directory, follow_symlinks=False)
        except FileNotFoundError:
            return
        if Path(git(path, "rev-parse", "--show-toplevel")) != self.vault:
            raise StateError("The ENGIE task ledger must stay inside the registered Git owner")

    @contextmanager
    def _directory(self, *, tasks: bool = False, create: bool = False) -> Iterator[int | None]:
        """Traverse the fixed location by descriptor, without following any links."""
        flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
        with ExitStack() as handles:
            directory = os.open(self.vault, flags)
            handles.callback(os.close, directory)
            info = os.fstat(directory)
            if (info.st_dev, info.st_ino) != self.owner:
                raise StateError("The registered vault filesystem identity changed")
            path = ENGIE_LEDGER / "tasks" if tasks else ENGIE_LEDGER
            current = self.vault
            for index, part in enumerate(path.parts):
                try:
                    child = os.open(part, flags, dir_fd=directory)
                except FileNotFoundError:
                    if not create:
                        yield None
                        return
                    try:
                        os.mkdir(part, 0o700, dir_fd=directory)
                    except FileExistsError:
                        pass
                    child = os.open(part, flags, dir_fd=directory)
                handles.callback(os.close, child)
                _require_exact_entry(directory, part)
                current /= part
                self._require_vault_owner(current, child)
                if index >= len(ENGIE_PRIVATE.parts):
                    self._private_entry(child, directory=True)
                directory = child
            yield directory

    @contextmanager
    def _lock_file(self, *, write: bool = False, create: bool = False) -> Iterator[int | None]:
        with self._directory(create=create) as directory:
            if directory is None:
                yield None
                return
            flags = os.O_NOFOLLOW | os.O_NONBLOCK | (os.O_RDWR if write else os.O_RDONLY)
            try:
                descriptor = os.open(".lock", flags | (os.O_CREAT if create else 0),
                                     0o600, dir_fd=directory)
            except FileNotFoundError:
                if create:
                    raise
                yield None
                return
            try:
                self._private_entry(descriptor, directory=False)
                yield descriptor
            finally:
                os.close(descriptor)

    @contextmanager
    def _lock(self) -> Iterator[None]:
        with self._lock_file(write=True) as descriptor:
            if descriptor is None:
                raise StateError("The ENGIE task ledger is absent")
            with _flock(descriptor, shared=False):
                yield

    @contextmanager
    def _observe(self, *, required: bool = False) -> Iterator[None]:
        with self._lock_file() as descriptor:
            if descriptor is None:
                if required:
                    raise StateError("The ENGIE task ledger is absent")
                yield
            else:
                with _flock(descriptor, shared=True):
                    yield

    @contextmanager
    def _begin_locked(self, root: Path) -> Iterator[list[dict[str, Any]]]:
        # Make the private lock visible first. Take existing general locks before
        # locking it, in the same order as a general begin observing this ledger.
        # If a general lock does not exist yet, its first writer will see this
        # private lock file and hold a shared lock before checking for collisions.
        default = Store(default_state_dir(), read_only=True)
        configured = Store(read_only=True)
        legacy = [default] if configured.root == default.root else [default, configured]
        with self._lock_file(write=True, create=True) as descriptor, ExitStack() as observers:
            for store in legacy:
                observers.enter_context(store._observe())
            with _flock(descriptor, shared=False):
                yield [task for store in legacy for task in store.list_tasks()]

    def _names(self) -> list[str]:
        with self._directory(tasks=True) as directory:
            return ([] if directory is None else
                    sorted(Path(name).stem for name in os.listdir(directory) if name.endswith(".json")))

    def _read_text(self, path: Path) -> str:
        with self._directory(tasks=True) as directory:
            if directory is None:
                raise FileNotFoundError(path.name)
            descriptor = os.open(path.name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
            with os.fdopen(descriptor, "r", encoding="utf-8") as handle:
                self._private_entry(handle.fileno(), directory=False)
                return handle.read()

    def _read(self, task_id: str) -> dict[str, Any]:
        task = super()._read(task_id)
        assignments = task.get("assignments")
        if (task.get("root") != str(self.vault) or task.get("ledger") != ENGIE_ROUTE
                or task.get("mode") != "local" or task.get("target") is not None
                or "publication_message" in task or task.get("publication") != {}
                or not isinstance(assignments, dict)
                or not assignments or task.get("paths") != list(assignments)
                or any(not engie_learning_path(name) for name in assignments)):
            raise StateError("The stored ENGIE task violates its private local scope")
        return task

    def get(self, task_id: str) -> dict[str, Any]:
        """Read an atomic ENGIE task record without modifying the private lock."""
        return self._read(task_id)

    def begin(self, task_id: str, root: str | Path, requirement: str,
              assignments: Mapping[str, str], **options: Any) -> dict[str, Any]:
        """Admit only exact capture destinations in an explicitly local task."""
        if Path(root) != self.vault:
            raise StateError("ENGIE learning requires the exact registered vault root")
        if options.get("mode") != "local":
            raise StateError("ENGIE learning requires mode 'local'")
        if (not isinstance(assignments, Mapping) or not assignments
                or any(not isinstance(name, str) or not engie_learning_path(name) for name in assignments)):
            raise StateError("ENGIE learning requires exact private topic and daily notes")
        self._path(task_id)
        return super().begin(task_id, root, requirement, assignments, **options)

    def save_locked(self, task: dict[str, Any]) -> None:
        """Write an owner-only record atomically inside the fixed tasks directory."""
        destination = self._path(task["id"])
        with self._directory(tasks=True, create=True) as directory:
            temporary = ".task-" + uuid.uuid4().hex
            descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL,
                                 0o600, dir_fd=directory)
            try:
                _write_record(descriptor, task)
                os.replace(temporary, destination.name, src_dir_fd=directory, dst_dir_fd=directory)
                os.fsync(directory)
            finally:
                try:
                    os.unlink(temporary, dir_fd=directory)
                except FileNotFoundError:
                    pass
