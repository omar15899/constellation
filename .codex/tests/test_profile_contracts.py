"""Validate installed native contracts, without mutating repos or using network."""
import ast
import json
from pathlib import Path
import re
import subprocess
import sys
import unittest

HUB = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(HUB / '.codex'))
from ecosystem.runtime.agent_policy import AgentPolicy, _assignment, _statements


class ProfileContracts(unittest.TestCase):
    def test_native_roles_inherit_execution_settings(self):
        expected = {f'ecosystem_{name}' for name in ('coder', 'researcher', 'reviewer',
                    'security_reviewer', 'verifier', 'mathematician', 'counterexample', 'editor')}
        actual = set()
        for profile in sorted((HUB / '.codex/ecosystem/agents').glob('*.toml')):
            # These profiles deliberately use only string assignments. Refuse
            # execution overrides or tables, including on Python without tomllib.
            fields = {}
            for _, _, statement in _statements(profile.read_text()):
                if not statement:
                    continue
                keys, value = _assignment(statement)
                self.assertEqual(len(keys), 1, profile)
                self.assertNotIn(keys[0], fields, profile)
                fields[keys[0]] = ast.literal_eval(value)
            self.assertEqual(set(fields), {'name', 'description', 'developer_instructions'}, profile)
            self.assertTrue(all(isinstance(value, str) and value.strip() for value in fields.values()), profile)
            self.assertNotIn(fields['name'], actual)
            actual.add(fields['name'])
        self.assertEqual(actual, expected)

    def test_installed_profiles(self):
        policy = AgentPolicy(HUB, 'profile-contract-read-only')
        registry = json.loads((HUB / '.codex/repositories.json').read_text())
        self.assertEqual(registry['schema_version'], 1)
        entries = registry['repositories']
        self.assertEqual(len({e['path'] for e in entries}), len(entries))
        self.assertIn({'path': '.', 'management': 'native'}, entries)
        for entry in entries:
            root = HUB / entry['path']
            if entry['management'] != 'native' or not root.is_dir():
                continue  # Hub-only clones need not contain the other projects.
            with self.subTest(repository=entry['path']):
                actual = subprocess.check_output(
                    ['git', '-C', str(root), 'rev-parse', '--show-toplevel'], text=True).strip()
                self.assertEqual(Path(actual).resolve(), root.resolve())
                profile = root / '.codex/profile.json'
                if profile.exists() or profile.is_symlink():
                    self.assertFalse(profile.is_symlink())
                    self.assertEqual(json.loads(profile.read_text())['mode'], 'native')
                agents = (root / 'AGENTS.md').read_text()
                self.assertLess(len(agents.encode()), 9000)
                self.assertNotIn('GENERATED BY', agents)
                if entry['path'] != '.':
                    # Domain skills and tools are legitimate. Shared engine
                    # implementations and identical shared profiles are not.
                    for filename in ('workflow.py', 'workspace.py', 'dispatch.py', 'review_gate.py'):
                        local_engine = root / '.codex' / filename
                        if local_engine.exists():
                            shared_engine = HUB / '.codex/ecosystem/runtime' / filename
                            self.assertNotEqual(local_engine.read_bytes(), shared_engine.read_bytes())
                    shared_profiles = {path.read_bytes() for path in
                                       (HUB / '.codex/ecosystem/agents').glob('*.toml')}
                    for local_profile in (root / '.codex/agents').glob('*.toml'):
                        self.assertNotIn(local_profile.read_bytes(), shared_profiles)
                for filename in ('AGENTS.md', '.codex/README.md', '.codex/PROJECT.md'):
                    source = root / filename
                    if not source.exists():
                        continue
                    for link in re.findall(r'\]\(([^)]+)\)', source.read_text()):
                        if '://' not in link and not link.startswith('#'):
                            self.assertTrue((source.parent / link.split('#', 1)[0]).exists(),
                                            f'{source}: missing {link}')
        self.assertTrue(policy.inspect()['matches'], 'Native concurrency configs drifted from agent-policy.json')


if __name__ == '__main__':
    unittest.main()
